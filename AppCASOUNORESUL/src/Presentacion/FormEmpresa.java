    private void limpiarBotones(){
        this.txtPlaca.setText("");
        this.txtConsumo.setText("");
        this.txtCarga.setText("");
        this.txtAreaMost.setText("");
    }
    
    private void cmdRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmdRegistrarActionPerformed
        // TODO add your handling code here:
        
        String placa=this.txtPlaca.getText();
        String carga=this.txtCarga.getText();
        String consumo=this.txtConsumo.getText();
        if(placa.isEmpty()||carga.isEmpty()||consumo.isEmpty()){
            Ventana.imp("por favor digite toda la informacion", "sistema");
            this.limpiarBotones();
            return;
        }
        String aux="";
        aux=this.myEmpresa.registarCamion(placa, Integer.parseInt(carga), Float.parseFloat(consumo));
        this.txtAreaMost.setText(aux);
        if(!this.txtAreaMost.getText().isEmpty()){
            Ventana.imp("Clik en continuar","sistema");
            this.limpiarBotones();
        }
            
    }//GEN-LAST:event_cmdRegistrarActionPerformed

