    private void cmdValidarPlacaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmdValidarPlacaActionPerformed
        // TODO add your handling code here:
        
        if (this.txtPlaca.getText().isEmpty()){
            Ventana.imp("DIGITE UNA PLACA: ","sistema");
            return;
        }
        if(this.myEmpresa.validarPlaca(this.txtPlaca.getText())){
             Ventana.imp("PLACA YA EXISTE, DIGITAR OTRA ", "sistema");
             this.txtPlaca.setText(""); 
             return;
        }
      Ventana.imp("Continuar con el registro ", "sistema"); 
     
      
    }//GEN-LAST:event_cmdValidarPlacaActionPerformed

    private void cmdMejorCamionTransportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmdMejorCamionTransportarActionPerformed
        // TODO add your handling code here:
       
       int carga=Ventana.leerInt("INGRESE CARGA A TRANSPORTAR: ");
       if(carga!=0){
           this.txtAreaMost.setText(this.myEmpresa.buscarCamionCarga(carga)); 
           return;
       }
       if(!this.txtAreaMost.getText().isEmpty()){
             Ventana.imp("Clik en continuar","sistema");
            this.limpiarBotones();
    }//GEN-LAST:event_cmdMejorCamionTransportarActionPerformed
    }
    
